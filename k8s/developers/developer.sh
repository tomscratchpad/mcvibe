#!/usr/bin/env bash
# Onboard / offboard a developer: one namespace each (IaC: the generated
# overlay under users/<slug>/ is committed; CI applies users/*).
#
#   developer.sh add        <username>  # write users/<slug>/, apply it, issue the LLM gateway key
#   developer.sh render     <username>  # write users/<slug>/ only (review / PR)
#   developer.sh rotate-key <username>  # replace the developer's LLM gateway key
#   developer.sh remove     <username>  # revoke the key, delete the namespace (ALL their sandboxes) and the overlay
#   developer.sh ns         <username>  # print the namespace name
#
# LLM gateway key: one LiteLLM virtual key per developer (alias dev-<slug>,
# user_id = <username>), stored as Secret litellm-key in their namespace and
# injected by the namespace's SandboxTemplate. Developers have no RBAC on
# Secrets. The key is scoped (Claude models), budgeted per day, rate-limited,
# and accepted by LiteLLM only from session namespaces (NetworkPolicy).
# Needs: cluster-admin kubeconfig (reads the LiteLLM master key).
#
# <username> is exactly what the API server authenticates (with OIDC:
# "oidc:alice@corp.com"); it becomes the owner annotation and RoleBinding
# subject. The namespace is sbx-<slug>, same rule as `sbx` (cli/internal/sandbox
# OwnerSlug): drop an "idp:" prefix and "@domain", lowercase, [a-z0-9-], <= 20 chars.
set -euo pipefail
cd "$(dirname "$0")"

slug() {
  local s
  s=$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')
  s=${s##*:}
  [[ $s == ?*@* ]] && s=${s%%@*}
  s=$(printf '%s' "$s" | sed -E 's/[^a-z0-9-]+/-/g; s/^-+//; s/-+$//')
  s=${s:0:20}; s=$(printf '%s' "$s" | sed -E 's/-+$//')
  printf '%s' "${s:-anon}"
}

cmd=${1:?usage: $0 add|render|rotate-key|remove|ns <username>}
user=${2:?username}
ns="sbx-$(slug "$user")"
dir="users/${ns#sbx-}"

# Per-developer limits (USD at API list price; a usage meter in subscription mode).
DEV_BUDGET_USD="${DEV_BUDGET_USD:-50}"
DEV_RPM="${DEV_RPM:-120}"
DEV_TPM="${DEV_TPM:-4000000}"
DEV_PARALLEL="${DEV_PARALLEL:-8}"

# litellm <path> <json>: admin call to the LLM gateway (port-forward + master key).
litellm() {
  local master port pf out
  master=$(kubectl -n llm-gateway get secret litellm -o jsonpath='{.data.master-key}' | base64 -d)
  port=$((20000 + RANDOM % 10000))
  kubectl -n llm-gateway port-forward svc/litellm "$port:4000" >/dev/null 2>&1 & pf=$!
  for _ in $(seq 50); do curl -s -o /dev/null "http://127.0.0.1:$port/health/liveliness" && break; sleep 0.2; done
  out=$(curl -sS -H "Authorization: Bearer $master" -H 'Content-Type: application/json' "http://127.0.0.1:$port$1" -d "$2")
  kill $pf 2>/dev/null; wait $pf 2>/dev/null || true
  printf '%s' "$out"
}

issue_key() {
  local alias="dev-${ns#sbx-}" key
  litellm /key/delete "{\"key_aliases\":[\"$alias\"]}" >/dev/null || true
  key=$(litellm /key/generate "{
      \"key_alias\": \"$alias\",
      \"user_id\": \"$user\",
      \"models\": [\"claude-*\", \"anthropic/*\"],
      \"max_budget\": $DEV_BUDGET_USD, \"budget_duration\": \"1d\",
      \"rpm_limit\": $DEV_RPM, \"tpm_limit\": $DEV_TPM, \"max_parallel_requests\": $DEV_PARALLEL,
      \"metadata\": {\"namespace\": \"$ns\", \"owner\": \"$user\"}
    }" | python3 -c 'import json,sys; print(json.load(sys.stdin)["key"])')
  kubectl -n "$ns" create secret generic litellm-key --from-literal=api-key="$key" \
    --dry-run=client -o yaml | kubectl apply -f - >/dev/null
  echo "issued LLM gateway key $alias for $user (\$$DEV_BUDGET_USD/day, ${DEV_RPM} rpm); running sandboxes keep the old key until recreated"
}

revoke_key() {
  litellm /key/delete "{\"key_aliases\":[\"dev-${ns#sbx-}\"]}" >/dev/null || true
  echo "revoked LLM gateway key dev-${ns#sbx-}"
}

owner_of() { kubectl get ns "$1" -o jsonpath='{.metadata.annotations.agent-platform/owner-username}' 2>/dev/null || true; }

render() {
  if [[ -f $dir/kustomization.yaml ]] && ! grep -qF "value: \"$user\"" "$dir/kustomization.yaml"; then
    echo "error: $dir already belongs to another username (slug collision); pick an explicit name" >&2; exit 1
  fi
  mkdir -p "$dir"
  cat > "$dir/kustomization.yaml" <<EOF
# Generated by developer.sh for $user. Commit this file; CI applies users/*.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
namespace: $ns
resources:
- ../../base
patches:
- target: { kind: Namespace }
  patch: |-
    - op: replace
      path: /metadata/annotations/agent-platform~1owner-username
      value: "$user"
- target: { kind: RoleBinding, name: sandbox-developer }
  patch: |-
    - op: replace
      path: /subjects/0/name
      value: "$user"
EOF
  echo "wrote $dir/kustomization.yaml ($ns)"
}

case $cmd in
ns) echo "$ns" ;;
render) render ;;
add)
  existing=$(owner_of "$ns")
  if [[ -n $existing && $existing != "$user" ]]; then
    echo "error: namespace $ns is owned by $existing" >&2; exit 1
  fi
  render
  kubectl apply -k "$dir"
  issue_key
  ;;
rotate-key)
  [[ $(owner_of "$ns") == "$user" ]] || { echo "error: $ns is not owned by $user" >&2; exit 1; }
  issue_key
  ;;
remove)
  existing=$(owner_of "$ns")
  if [[ -n $existing && $existing != "$user" ]]; then
    echo "error: namespace $ns is owned by $existing, not $user" >&2; exit 1
  fi
  revoke_key
  kubectl delete ns "$ns" --ignore-not-found --wait=true
  rm -rf "$dir"
  echo "removed $ns"
  ;;
*) echo "unknown command $cmd" >&2; exit 2 ;;
esac
